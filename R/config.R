#' 应用根目录
#'
#' 优先取环境变量（app.R 启动时写入），否则回落到当前工作目录 ——
#' Shiny Server 就是在应用目录里启动 R 进程的。
dsapp_app_dir <- function() {
  p <- Sys.getenv("DSAPP_APP_DIR", "")
  if (nzchar(p)) {
    return(normalizePath(p, mustWork = FALSE))
  }
  normalizePath(getwd(), mustWork = FALSE)
}

#' 定位 conda 可执行文件
#'
#' 不能只靠 Sys.which("conda")：应用以 shiny 身份运行，而 conda 是装在
#' 某个用户的 home 下的，只有交互式 shell 才会被 `conda init` 写进 PATH。
#' 实测 /home/biomamba/miniconda3 是 775、conda 本身 775，shiny 能读能执行
#' —— 但它的 envs/ 目录 shiny 写不进去，所以建环境时必须用 `conda create -p`
#' 指到我们自己可写的路径（见 R/envs.R）。
#'
#' 返回找到的第一个，找不到返回 ""（调用方负责给出可读的报错）。
dsapp_find_conda <- function() {
  explicit <- Sys.getenv("DSAPP_CONDA_BIN", "")
  if (nzchar(explicit) && file.exists(explicit)) {
    return(explicit)
  }

  candidates <- c(
    Sys.which("conda"),
    "/opt/conda/bin/conda",
    "/opt/miniconda3/bin/conda",
    "/opt/anaconda3/bin/conda",
    "/usr/local/bin/conda",
    # ★ V16.6 item 5：macOS 的两个 Homebrew 前缀。
    #   ⚠️ Apple Silicon 的 Homebrew 装在 **/opt/homebrew**，不是 Intel 那套
    #      /usr/local —— 少了这一条，M 系列机器上"环境"页会明说找不到 conda，
    #      而用户明明装了（他只是用 brew 装的）。这正是上面那段注释里
    #      "只有交互式 shell 才会被 conda init 写进 PATH" 的同一个坑换个平台。
    "/opt/homebrew/bin/conda",
    # brew install --cask miniconda 装出来的真身在这个位置（bin/conda 是个
    # 指向它的软链，但有些装法只留了这一个）
    "/opt/homebrew/Caskroom/miniconda/base/bin/conda",
    file.path(Sys.getenv("HOME", ""), "miniconda3/bin/conda"),
    file.path(Sys.getenv("HOME", ""), "anaconda3/bin/conda"),
    # Apple Silicon 上更常见的两个（miniforge 是 brew 之外的默认推荐）
    file.path(Sys.getenv("HOME", ""), "miniforge3/bin/conda"),
    file.path(Sys.getenv("HOME", ""), "mambaforge/bin/conda"),
    # 这台机器上 conda 实际所在的位置（见上）
    "/home/biomamba/miniconda3/bin/conda"
  )
  candidates <- candidates[nzchar(candidates)]
  hit <- candidates[file.exists(candidates) & file.access(candidates, 1) == 0]
  if (length(hit)) hit[[1]] else ""
}

#' 单次执行允许 BLAS/OMP 开几个线程
#'
#' ⚠️ 这个默认值不是"性能调优"，是**能不能跑起来**的问题，2026-09-14 自检
#'    红了两条才查出来：
#'
#'    R 一加载矩阵库（OpenBLAS）就会按**核数**开线程，这台机器是 60 核 ——
#'    也就是每个任务默认想开 60 个线程。而执行包装脚本里有 `ulimit -u`（见
#'    dsapp_wrapper_script），那个限制在 Linux 上是**按 uid 全局算的**，不是
#'    按任务算的：应用以 shiny 一个身份跑所有用户的代码，任何时刻该 uid 名下的
#'    线程总数都会被拿来跟这个上限比。于是一个任务开 60 个线程，几个任务并发
#'    就把额度吃光，之后**所有人的**任务在 `pthread_create` 上失败 ——
#'    报错是 "Resource temporarily unavailable"，看起来跟代码毫无关系。
#'
#'    钉住线程数把"一个任务能吃掉多少进程额度"变成常数，`ulimit -u` 才重新
#'    变成一道有意义的闸门。8 是生信常见矩阵运算的收益拐点（DESeq2/limma
#'    在 8 线程以上基本不再变快），要和别的任务抢 CPU 时也更公平。
#'
#'    本机自用（Windows 本地运行，见 item 6）想在单机上吃满核，改
#'    DSAPP_EXEC_THREADS 即可 —— 那里没有多用户共享 uid 的问题。
#'
#' CPU 核数 —— **进程内只问一次**（拿不到返回 NA）
#'
#' ★ V15.10 item 1：这个函数是被一行性能测量逼出来的。2026-10-02 量
#'    `dsapp_config()`：**7.6 ms/次**，其中 6.9 ms 全在这一句
#'    `parallel::detectCores(logical = TRUE)` 上 —— Linux 上它是**真的
#'    fork 一个 shell** 去跑 getconf（不是读 /proc），这台 60 核的机器上
#'    单是这一下就要 6.9 ms。
#'
#'    它藏在 dsapp_config() 里，于是**每一次读配置**都要付这 6.9 ms，而
#'    读配置的地方有 245 处：每个渲染格子、每个定时器醒来、每一次
#'    `dsapp_db(cfg())`。流式输出时 output$streaming 每 200ms 重画一次，
#'    每拍白烧 7.6 ms；线上 worker"什么都不干"时那 3–6% 的 CPU 也来自这里。
#'
#' ⚠️ 为什么缓存它没有过期问题：核数在**一个进程的生命周期里是常数**。
#'    热插 CPU、容器改 quota，都不该让已经在跑的 R 中途换一个数 —— 那个数
#'    已经被用来钉 BLAS 线程数了（见 dsapp_default_threads），中途变反而
#'    是有害的。所以缓存的是"问一次"这件事本身，不是某个会过期的业务值。
#'
#' ⚠️ 拿不到时返回 **NA**，不编一个数：`dsapp_host_identity()` 会把"不知道
#'    几核"如实显示出来（那个界面上的注释说过，"编一个数"比"不知道"更糟）。
#'    要默认值的地方（dsapp_default_threads）自己回落。
.dsapp_cores_env <- new.env(parent = emptyenv())

dsapp_cores <- function() {
  if (isTRUE(.dsapp_cores_env$done)) return(.dsapp_cores_env$n)
  n <- suppressWarnings(as.integer(parallel::detectCores(logical = TRUE)))
  if (is.na(n) || n < 1L) n <- NA_integer_
  .dsapp_cores_env$n <- n
  .dsapp_cores_env$done <- TRUE
  n
}

#' @return 整数，至少 1
dsapp_default_threads <- function() {
  n <- dsapp_cores()
  if (is.na(n) || n < 1L) n <- 4L
  min(8L, n)
}

#' 读取配置
#'
#' ★ V15.10 item 1：结果按**环境变量指纹**缓存。
#'
#' 这一格的注释原来写着「每次调用都重新读环境变量。配置项很少，开销可以
#' 忽略」—— 2026-10-02 量了，**开销不可以忽略**：7.6 ms/次，其中 6.9 ms
#' 是 dsapp_default_threads() → dsapp_cores() 那句 fork（见那边的说明）。
#' 而全仓库有 **245 处**在调它，热路径全在里面：
#'   · R/mod_chat.R:4191  output$streaming 每 200ms 一拍 `img_cfg = cfg()`
#'   · R/mod_chat.R:2537  output$history 每次重画
#'   · 几十处 `dsapp_db(cfg())`、每个定时器醒来各一遍
#' 也就是：**用户打字的时候，worker 每 200ms 白烧 7.6 ms**；空闲时那
#' 3–6% 的 CPU 也是这么来的。缓存之后同样一次调用约 0.3 ms（指纹本身）。
#'
#' ⚠️⚠️ 必须带指纹，不能"进程内算一次就完"。运行期确实会改环境变量：
#'    R/jobs.R:53 与 R/detach.R:463/894 会 `Sys.setenv(DSAPP_DATA_ROOT=...)`
#'    切数据根，自检里也有"设 A 拿一份配置、设 B 再拿一份"来回切的用例
#'    （selftest.R:12525 起那一整段多根的验证）。不带指纹的缓存会让那些
#'    地方**读到上一个根** —— 表现是往错误的数据目录里写东西，而且不报错。
#'
#' ⚠️ 指纹取 `Sys.getenv()` 的**全量转储**，不是手挑几个 DSAPP_*。手挑的
#'    清单会随着以后新增的读取项静默过期（新加一个 DSAPP_FOO 的读取，
#'    缓存却还按老键命中 —— 正是最坏的一种错）。全量转储这条路，任何
#'    环境变量的任何变化都会让缓存当场失效，不需要谁记得来改这里。
#'
#' ⚠️ 唯一的取舍：**文件系统**类的取值（应用目录旁边的 data/ 可不可写、
#'    conda 在不在）只在未命中时重算，也就是同一套环境变量下、一个进程
#'    里只算一次。生产上 DSAPP_DATA_ROOT / DSAPP_CONDA_BIN 都写死在
#'    .Renviron 里，这条路径根本不走；真有人在运行期把 data/ 的权限改掉，
#'    症状是建库/写文件**报错**（有声），不是静默写错地方。
#'
#' ⚠️ 返回值是**共享**的一个 list。调用方改它（`dsapp_config_user()` 的
#'    `cfg$files_dir <- ...`）走的是 R 的写时复制，不会污染缓存 —— 但也
#'    别在别处依赖"拿到的一定是个新对象"。
dsapp_config <- function() {
  ev <- Sys.getenv()
  fp <- paste(names(ev), ev, sep = "=", collapse = "\n")
  if (!is.null(.dsapp_cfg_cache$fp) && identical(.dsapp_cfg_cache$fp, fp))
    return(.dsapp_cfg_cache$cfg)
  cfg <- .dsapp_config_build()
  .dsapp_cfg_cache$fp <- fp
  .dsapp_cfg_cache$cfg <- cfg
  cfg
}

.dsapp_cfg_cache <- new.env(parent = emptyenv())

#' 读一遍配置（不走缓存）—— `dsapp_config()` 的实际实现
.dsapp_config_build <- function() {
  app_dir <- dsapp_app_dir()

  # 数据目录默认放在应用目录下。注意：应用以 shiny 用户运行，这个目录
  # 必须对 shiny 可写，否则建库和上传都会失败。
  #
  # ⚠️ V13.2 item 1：打包成桌面版 / 装到 Program Files 之后，**应用目录
  #    是不可写的**，这个默认值当场就建不出库来。所以判定挪进了
  #    dsapp_default_data_root()：环境变量 > 应用目录旁边 > 用户私有目录。
  #    服务器上应用目录可写，走的是第一条，行为和以前完全一样。
  # ★ V13.7 item 2：`fallback = TRUE` 意思是"应用目录旁边建不出来，数据被
  #   放到了用户私有目录"。R/platform.R 里那段注释写着"调用方（界面/启动器）
  #   应该把这件事说出来"—— 但这里一直只取了 `$path`，那个标志被丢掉了，
  #   于是**没有任何人知道**数据其实在别处。用户找不到自己的文件时会以为
  #   数据丢了，而这本来是一句日志就能说清的事。
  #
  # ⚠️ 这里只能 message()，**不能** dsapp_audit()：审计的默认参数是
  #    `cfg = dsapp_config()`，在这里调它就是无限递归。而且这个函数每次
  #    读配置都会被调一次，所以用一个 option 挡着，只喊一次。
  dr <- dsapp_default_data_root(app_dir)
  data_root <- dr$path
  if (isTRUE(dr$fallback) && !isTRUE(getOption("dsapp.data_root_fallback_said"))) {
    options(dsapp.data_root_fallback_said = TRUE)
    message(sprintf(paste0(
      "[dsapp] 应用目录下建不出 data/（多半是只读安装目录），",
      "数据目录已自动改用 %s。想固定在别处就设 DSAPP_DATA_ROOT。"), data_root))
  }

  as_num <- function(key, default) {
    v <- suppressWarnings(as.numeric(Sys.getenv(key, "")))
    if (is.na(v)) default else v
  }

  # ★ V14 item 7：环境变量里那个布尔开关怎么读。
  #
  # ⚠️ 认的是一组**肯定**写法，认不出来一律回落 default。别写成
  #    `!identical(tolower(v), "false")` 那种"没写 false 就算 true"的写法：
  #    那样 `DSAPP_EXEC_GPU=`（设成空串，.Renviron 里注释掉一半的样子）
  #    会被读成 TRUE，而它看起来像是"关着"。开关类的东西读错方向的代价是
  #    静默把资源敞开，所以这里宁可保守。
  as_flag <- function(key, default) {
    v <- tolower(trimws(Sys.getenv(key, "")))
    if (!nzchar(v)) return(default)
    if (v %in% c("1", "true", "yes", "on", "y", "t")) return(TRUE)
    if (v %in% c("0", "false", "no", "off", "n", "f")) return(FALSE)
    default
  }

  list(
    app_dir   = app_dir,
    data_root = data_root,

    db_path   = file.path(data_root, "dsapp.sqlite3"),
    # 文件管理区。⚠️ V3 agent 改造后它**只是用户上传区** —— 任务产物默认
    # 留在对话自己的工作区里，要进这里必须显式「发布」。见 utils.R 的
    # dsapp_ws_dir() 和 executor.R 顶部的说明。
    # 进门方式：
    #   "login" —— **默认**（V6 item 3）。登录页那一套：注册 / 密码 / 恢复码。
    #   "auto"  —— 打开就直接进，用 id 最小的那个启用账号
    #              （见 dsapp_default_user）。没有登录页，不写 cookie，
    #              也不 reload —— 整件事在服务端做完，浏览器里的 JS
    #              是死是活都不影响进门。
    #
    # ⚠️ 默认值 V5.1 时是 "auto"，V6 改回 "login"。这不是反复无常：
    #    "auto" 是**所有人共用一个账号**，而 V6 的三件事全都建立在
    #    "人跟人对得上"之上 ——
    #      · item 1 按账号记住 API Key（共用账号 = 共用 Key）
    #      · item 4 按账号分配硬件资源（共用账号 = 配额形同虚设）
    #      · V3 起每个对话一块隔离工作区（共用账号 = 谁都进得去谁的工作区）
    #    auto 模式下这些不是"弱一点"，是**完全不成立**。
    #
    # ⚠️ 改成 login 之后，唯一不能出错的是"进得去"。两道兜底：
    #      · 库里一个账号都没有 → 直接落到**注册**页（见 app.R 的 no_users），
    #        全新部署照样进得去，第一个注册的就是管理员。
    #      · 万一登录这一套本身坏了 —— 在 .Renviron 里设
    #        DSAPP_AUTH_MODE=auto 就能退回直接进入，不需要改代码。
    #    "auto" 模式下 URL 上加 ?login=1 仍然能看一眼登录页（排查时用）。
    # 无论哪种模式，URL 上的 ?u=<令牌> 都有效。
    auth_mode = Sys.getenv("DSAPP_AUTH_MODE", "login"),

    # ---- 文件管理区（V13 item 6 起**按账号隔离**）-------------------------
    #
    # ★ 用户原话：「文件管理区不用所有人可见，每个账号显示自己的管理区就好」。
    #   V5 到 V12 它一直是**所有人共用**的（见 files.R 旧的文件头：那个选择
    #   在"没有账号"的年代是对的 —— 生信数据要能互相引用）。有了账号体系、
    #   又有了 V12 的产物自动同步之后，共用区里开始堆**私人的分析产物**，
    #   再共用就说不通了。
    #
    # 两个字段，别搞混：
    #   · files_root —— 物理父目录（data/files）。所有账号的管理区都在它
    #     下面，形如 data/files/u3/。**只有迁移代码和管理页的统计会碰它。**
    #   · files_dir  —— 当前账号**正在用的那个根**。files.R / mod_files.R /
    #     executor.R 里那几十处 `cfg$files_dir` 说的都是它。
    #
    # ⚠️⚠️ 这里给的默认值是 `files_root/_anon`，一个**永远是空的**目录。
    #    为什么不用 files_root 本身：那是一颗地雷。所有取 cfg 的地方只要
    #    忘了带上账号，就会拿到"所有人的管理区的父目录" —— 列出来是一串
    #    u1、u3、u7，而只要名字里带上 `u3/xxx.csv` 就能把别人的文件读走。
    #    给 _anon 之后，同样的疏漏表现为**列表是空的**：错得响、错得安全，
    #    而不是错得看不见。要拿到某个账号的管理区，显式走
    #    dsapp_config_user() / dsapp_config_sid()。
    files_root = Sys.getenv("DSAPP_FILES_ROOT", file.path(data_root, "files")),
    files_dir  = file.path(Sys.getenv("DSAPP_FILES_ROOT",
                                      file.path(data_root, "files")), "_anon"),
    # 每个对话一块可写工作区（data/workspaces/chat-<sid>）。这是代码实际
    # 执行的地方，也是产物默认的落脚点。
    ws_root   = Sys.getenv("DSAPP_WS_ROOT", file.path(data_root, "workspaces")),
    # 本地暂存目录。本地执行的 code 已经搬到 ws_root 下了，这里现在只剩
    # 远程执行打包上传时的中转（见 remote.R）。留着是因为那个场景确实
    # 需要一个一次性的本地目录，和工作区不是一回事。
    work_dir  = file.path(data_root, "work"),
    logs_dir  = file.path(data_root, "logs"),
    run_dir   = file.path(data_root, "run"),     # 流式输出的中转文件
    # 用户自建 conda 环境 + 包缓存。**必须在 shiny 可写的地方** ——
    # 这就是为什么不用 conda 默认的 envs/：那在 /home/biomamba 下，
    # shiny 只读。详见 R/envs.R 顶部。
    envs_root = Sys.getenv("DSAPP_ENVS_ROOT", file.path(data_root, "envs")),
    # ---- conda/mamba 的包缓存（V13.5 item 5：按运行身份分一份）-------------
    #
    # ⚠️ 这一格**不能**是所有运行身份共用的一份（原来就是 `data/conda_pkgs`
    #    本身，踩了坑）。libmamba 每次启动都会对 `<这里>/cache` 反复 chmod，
    #    而 chmod 只有**属主**能做 —— 靠 ACL 拿到 rwx 不算数。
    #    开发用 biomamba、线上跑 shiny，共用一份的话，**无论 chown 给谁，
    #    另一个人建环境时都必然 EPERM**：
    #
    #      critical libmamba filesystem error: cannot set permissions:
    #      Operation not permitted [.../data/conda_pkgs/cache]
    #
    #    分成 `u<uid>/` 之后，每个人用的那一份都是**自己建的**，
    #    属主天然正确，两个身份各跑各的，谁也不用改谁的权限。
    #    推理和实测过程写在 platform.R 的 dsapp_run_id() 上面。
    #
    # ⚠️ 代价是缓存不共享（同一份 repodata 两边各存一份，这台机器上约 600 MB）。
    #    这是**故意的**：共享的那点磁盘换来的是一建环境就崩，不划算。
    #    真有运维要合成一份，就把它 chown 给运行身份、再用这个环境变量指过去。
    conda_pkgs_dir = Sys.getenv(
      "DSAPP_CONDA_PKGS_DIR",
      file.path(data_root, "conda_pkgs", paste0("u", dsapp_run_id()))),
    # 「导出到本地电脑」生成的压缩包落在这里
    export_dir = file.path(data_root, "exports"),
    # 平台 logo（V10 item 3）。放这儿而不是 www/：www/ 是**代码**的一部分
    # （跟着归档、跟着部署走），而 logo 是**这台部署的**东西 —— 换个实验室、
    # 换套 VI 就该换图，不该逼着人改代码。这个目录整个通过 addResourcePath
    # 挂出去（见 app.R），丢一张图进去界面就会用，没有就落回原来的图标。
    logo_dir  = file.path(data_root, "logo"),

    conda = list(
      # 应用以 shiny 身份运行，它的 PATH 里没有 conda（conda 装在
      # /home/biomamba/miniconda3 下，只有交互式 shell 才 init）。
      # 所以这里要显式给候选路径，不能用 Sys.which() 了事。
      bin = dsapp_find_conda(),
      timeout = as_num("DSAPP_CONDA_TIMEOUT", 3600)
    ),

    ssh = list(
      bin     = Sys.getenv("DSAPP_SSH_BIN", "/usr/bin/ssh"),
      scp     = Sys.getenv("DSAPP_SCP_BIN", "/usr/bin/scp"),
      rsync   = Sys.getenv("DSAPP_RSYNC_BIN", "/usr/bin/rsync"),
      timeout = as_num("DSAPP_SSH_TIMEOUT", 3600)
    ),

    llm = list(
      base_url      = Sys.getenv("DSAPP_LLM_BASE_URL", "https://api.deepseek.com"),
      # ⚠️ 这里以前写的是 deepseek-chat，那个模型名 2026-07-24 已经下线了。
      # 不改的话，凡是没进过设置页的用户，第一句话就必然报错 —— 而"没进过
      # 设置页"恰恰是新用户。默认值必须指向当前真实存在的模型。
      # 详见 R/models.R 顶部的说明。
      default_model = Sys.getenv("DSAPP_LLM_DEFAULT_MODEL", "deepseek-flash"),
      # 单次请求的整体超时。生信长回答 + 慢网络，默认给足。
      # 思考模式下模型要先写一大段思维链，比非思考模式慢不少，别调太小。
      timeout       = as_num("DSAPP_LLM_TIMEOUT", 900)
    ),

    exec = list(
      # 墙钟超时：到点强杀整个进程组
      timeout   = as_num("DSAPP_EXEC_TIMEOUT", 1800),
      # 地址空间上限（MB）。生信分析吃内存，默认给大一些。
      mem_mb    = as_num("DSAPP_EXEC_MEM_MB", 16384),
      # CPU 时间上限（秒），和墙钟分开算：一个 sleep 循环不烧 CPU，
      # 但一个死循环会，两者都得管。
      cpu_sec   = as_num("DSAPP_EXEC_CPU_SEC", 1800),
      # ⚠️ RLIMIT_NPROC（ulimit -u）在 Linux 上是**按 uid 全局**算的，不是
      #    按任务算的 —— 应用以 shiny 一个身份跑所有用户的代码，所以这个数
      #    要和"同时跑的所有任务加起来"比。512 在钉住线程数（见
      #    dsapp_default_threads）之后够用；包装脚本里另有一道兜底：
      #    该 uid 当前已有的线程数超过这个值时，上限会被抬到"当前 + 余量"，
      #    否则连一次 fork 都过不去。
      max_procs = as_num("DSAPP_EXEC_MAX_PROCS", 512),
      # 单次执行能开的 BLAS/OMP 线程数（见 dsapp_default_threads）
      threads   = as_num("DSAPP_EXEC_THREADS", dsapp_default_threads()),
      # 单次执行产出的 stdout/stderr 上限，防止刷爆数据库
      max_output_kb = as_num("DSAPP_EXEC_MAX_OUTPUT_KB", 512),

      # ★ V14 item 7：**平台层面**的 GPU 默认开关。
      #
      # 用户原话：「在「配额与资源」上限中加一个设置用户是否能够使用 GPU
      # 资源的开关按钮」。管理页那个开关是**每账号**的（users.gpu_enabled，
      # NULL = 没设过 → 落到这里）。
      #
      # ⚠️⚠️ 默认 FALSE（不给用），这是**有意**选的，不是随手写的。
      #    GPU 是全机器最稀缺的那样东西（一般一张卡，同一时刻只能有一个
      #    任务真的在算），所以"默认能用"的代价是**任何人**跑一段
      #    `torch.cuda` 就能把卡占了，而占卡的人往往自己都不知道占了。
      #    生信流程里绝大多数步骤（QC、聚类、富集）根本不碰 GPU，
      #    真正需要的只有 cell2location / scVI 那一小撮 —— 让管理员按人开，
      #    比让所有人默认敞着要合理。
      #    ⚠️ 反过来说：这台机器**没有 GPU** 时（`ls /dev/nvidia*` 为空），
      #       这个开关不产生任何可观察的差别 —— 它是给"以后挂了卡"准备的，
      #       不是修一个当下的毛病。
      #
      # ⚠️ 它**只管本机执行**。用户选了「远程服务器」（代码在他自己的机器上
      #    跑）时**不看这一项** —— 那是他的硬件，我们的开关管不着，
      #    和 dsapp_task_submit 里"远程目标不查配额"是同一条道理。
      gpu       = as_flag("DSAPP_EXEC_GPU", FALSE)
    ),

    max_upload_mb = as_num("DSAPP_MAX_UPLOAD_MB", 2048),

    # ---- 解压上限（见 R/files.R 的 dsapp_archive_extract）------------------
    # 压缩包是**唯一**能让一次点击写出几十 G 的入口：一个 2 GB 的 tar.gz
    # 可以解出几百 G（还可能是故意构造的）。上传本身有 max_upload_mb 兜着，
    # 解开之后没有上限就等于没有防线。
    extract = list(
      max_bytes = as_num("DSAPP_EXTRACT_MAX_MB", 4096) * 1024^2,
      # 条目数上限：挡的是"几百万个小文件"——那种包不占多少字节，但能把
      # 文件系统拖垮，而且解完之后工作区里的 list.files 会慢到没法用。
      max_files = as_num("DSAPP_EXTRACT_MAX_FILES", 20000)
    ),

    # ★ Test_V15.2：**时区**。
    #
    # ⚠️ 这是本次唯一一处**故意不用 dsapp_now()** 的地方，理由值得写下来：
    #    库里所有时间戳都是 UTC（dsapp_now），这对"记录发生了什么"是对的。
    #    但「每天早上 8 点给我发文献速递」里的那个 8 点，是**用户墙上的
    #    8 点**。拿 UTC 去算的话，中国用户设的 8 点会在下午 4 点跑 ——
    #    而界面上显示的、用户脑子里想的都是 8 点，两边单看都没错。
    #
    #    所以 lit_subs.next_at 一律存**这个时区的本地时间字符串**，
    #    并且界面上把它显示出来（"下次：2026-09-29 08:00（Asia/Shanghai）"）。
    #    不显示的话，自托管在别的时区的部署上没人知道是哪个 8 点。
    #
    # 取不到时区名就退回 UTC —— 宁可跑在一个说得清的时区上，也不要
    # 一个"跟着服务器环境飘"的行为。空串会让 as.POSIXlt 用系统默认，
    # 那是第三回事，不选它。
    tz = {
      .tz <- trimws(Sys.getenv("DSAPP_TZ", ""))
      if (!nzchar(.tz)) {
        .tz <- tryCatch(Sys.timezone(), error = function(e) "")
        if (is.null(.tz) || is.na(.tz) || !nzchar(.tz)) .tz <- "UTC"
      }
      .tz
    },

    # ★ Test_V15.2：发信配置。
    #
    # ⚠️ 这是**平台级**凭据（一台机器一份），不是每账号一份 —— 和
    #    DSAPP_CONDA_BIN / DSAPP_PYTHON 同级。用户自己的邮箱是**收件人**
    #    （users.email），不是发件人。
    #
    # ⚠️ 没有 enabled 开关，见 R/mail.R 的 dsapp_mail_ready()：
    #    四个必填项配齐了就是开了，没配齐就是没开，界面整个不出现。
    #    多一个开关只会多出"开着但没配"的半成品状态。
    #
    # ⚠️ 密码在这里是**明文**，而且 .Renviron 必须能被 shiny 读到
    #    （DSAPP_DATA_ROOT 就是这么读的）—— 所以它对应用进程是可读的。
    #    这和"应用需要用"是同一个信任级别，加密它没有额外收益。
    #    完整论证见 R/mail.R 顶部第 4 节。
    mail = list(
      host      = trimws(Sys.getenv("DSAPP_SMTP_HOST", "")),
      port      = as_num("DSAPP_SMTP_PORT", 465),
      user      = trimws(Sys.getenv("DSAPP_SMTP_USER", "")),
      pass      = Sys.getenv("DSAPP_SMTP_PASS", ""),   # ⚠️ 不 trimws：密码前后的空格可能是真的
      from      = trimws(Sys.getenv("DSAPP_SMTP_FROM", "")),
      from_name = trimws(Sys.getenv("DSAPP_SMTP_FROM_NAME", "言出法随")),
      # auto / force / try / no。auto 按端口推（465→force，587→try）。
      # 自检的假 SMTP 服务器要用 "no"。
      ssl       = trimws(Sys.getenv("DSAPP_SMTP_SSL", "auto"))
    )
  )
}

#' 建立数据目录
#'
#' 幂等。应用启动时调一次；目录已存在就什么都不做。
dsapp_init_dirs <- function(cfg = dsapp_config()) {
  # ⚠️ 这里建的是 files_root（父目录）+ files_dir（_anon 占位），**不是**
  #    "当前账号的管理区" —— 启动时根本还没有账号。各账号的目录在
  #    dsapp_files_ensure() 里按需建。
  for (d in c(cfg$data_root, cfg$files_root, cfg$files_dir, cfg$ws_root,
              cfg$work_dir, cfg$logs_dir, cfg$run_dir,
              cfg$envs_root, cfg$conda_pkgs_dir, cfg$export_dir,
              cfg$logo_dir)) {
    if (!dir.exists(d)) {
      dir.create(d, recursive = TRUE, showWarnings = FALSE)
    }
  }

  # 目录建不出来通常意味着权限不对（比如以 shiny 运行但目录归别人）。
  # 这时候早点报错，比等到用户上传文件时才炸要好定位得多。
  if (!dir.exists(cfg$data_root)) {
    stop(sprintf("数据目录无法创建：%s\n  当前用户：%s",
                 cfg$data_root, Sys.info()[["user"]]))
  }
  dsapp_files_migrate(cfg)
  invisible(cfg)
}
