# ★★★ V15.13：流式正文的**发送速率上限**（字节/秒）—— 这是"做什么都卡"的根。
#
# 2026-10-03 线上实测（ss -tni 数那条 TCP 的 bytes_sent）：用户的连接被**持续**
# 灌 **31.7 KB/s**，而那条链路实测只能送 **3.65 KB/s** —— 常年超订 8 倍以上。
# 症状就是用户说的那两句：「频繁断联」+「做任何操作都很卡」：
#   · 发送队列永远是满的（ss 里 busy:518536ms，cwnd 被压到 3、重传 13.6%）；
#   · 用户点任何一下，它的响应都排在这一大堆积压**后面** → 界面像冻住；
#   · 队列一满，SockJS 的 ping 迟到 → close(3000) → 整页重载 → 又发一遍。
#
# 31.7 KB/s 是从哪来的：泵每 200ms 一拍（5 拍/秒），**只要这一拍收到了新正文**
# 就把整条消息重渲染一遍重发。实测渲染字节（拿 uid=1 那条 26 万字回复做样本）：
#     500 字 → 1087 B    2000 字 → 3412 B    3000 字 → 4692 B
# 也就是说正文还没到窗口上限时，**每一拍都要发 1~4.7 KB**，5 拍/秒 = 5~23 KB/s。
#
# ⚠️⚠️ **拿本机的假 LLM 量这一版，会低估 5 倍左右** —— 别被它骗了：
#   假 LLM 是一坨一坨吐字的（实测 ~270 字/秒、**约 1 秒一坨**），而泵是 5 拍/秒
#   —— 于是每 5 拍里只有 1 拍手里有新字，`draft()` 也只写 1 次。
#   实测（gate 埋点，2026-10-03）：本机 5 拍/秒的空转里只有 ~1 拍有字，
#   7 KB 的回复推 140 KB；同一份代码在**真模型**下每个 tick 都有新字，那才是
#   线上那个 31.7 KB/s。（想在本机复现生产形态：把片间隔压到 0.1s 左右。）
#   所以"本地只快了 1.4 倍"不等于"线上只快 1.4 倍"。
#
# ⚠️ 而且 `DSAPP_STREAM_BUDGET_B` 那条预算**在这种情况下根本没生效**：
#    output$streaming 里那个收缩循环的退出条件是 `!isTRUE(win$cut) || ...`
#    —— 正文短于 DSAPP_STREAM_WIN_MAX 时 cut 恒为 FALSE，于是**第一轮就 break**，
#    4.7 KB 照发。那个预算是给"长到要切窗口"的正文用的，管不到这里。
#    （两种修法：① 让预算无条件生效 —— 但那样一条 2000 字的短回复也会被切出
#      「前文 N 字没显示」，体验倒退；② 按速率发 —— 短回复整条照发，只是发得
#      慢一点。选了 ②。）
#
# 所以这里不给"每拍多少字节"，给**每秒多少字节**：链路实测 3.65 KB/s，留一半
# 给思维链增量、历史重渲染、以及别的输出，流式正文自己吃 2.5 KB/s。
# ⚠️ 这个数是**按今天那条最慢的链路**定的。链路变快了它不会自动跟上 ——
#    要动它，先回去看 meas_*.R 和 ss -tni，别凭感觉调。
