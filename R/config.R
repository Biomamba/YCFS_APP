# 往那条 50 KB/s 的链路上灌好几次 1 MB：1158 KB ÷ 50 KB/s ≈ **23 秒**，
# 而 node 那侧 SockJS 心跳只给 10 秒。超时的后果和上面那段一样：close(3000)
# → 客户端对干净关闭不重连 → 自愈整页重载 → 黑屏。
#
# 预算的来历：140 KB 左右在 50 KB/s 上约 3 秒，离 10 秒判据有 3 倍余量；
# 就算链路掉到 20 KB/s 也只有 7 秒。
DSAPP_HIST_BUDGET_C <- 50000L

# 无论预算怎么算，**最末尾这几条一定要渲染**：用户正在看的就是这一轮，
# 而单条回复本身可能有几万字（实测最长 29 KB 正文 ≈ 80 KB HTML）。
# 预算挨到它们身上时不缩 —— 宁可这一包超一点，也不能让刚回答完的那条
# 从眼前消失。
#
# ⚠️ 6 条不是随便定的：一轮问答在库里不止两条（用户 / 助手 / 工具结果 /
#    助手…），只保底两条的话，最后一条很可能正好是个执行结果气泡 ——
#    页面上看着就是"回答没了"。但也不能多：这几十条是**免预算**的
#    （见 render.R 的 dsapp_hist_window 规则①），保底多少条就直接决定
#    最坏那一包多大。6 条 × 单条最长（实测 29 KB 正文）≈ 175 KB ≈ 3.5 秒
#    @50 KB/s，够用；写 8 条时在 markdown 密的正文上量到 236 KB（4.7 秒），
#    离 10 秒的判据只剩 2 倍余量。
DSAPP_HIST_MIN_MSG <- 6L

# 最末尾这两条**任何情况下**都渲染（连硬上限都不管）：它们就是用户眼前
# 这一轮，少了它们页面看着像坏了。
DSAPP_HIST_FLOOR_MSG <- 2L

# 保底那一段（末尾 MIN_MSG 条）总共允许超预算多少倍。
#
# ⚠️ 这个数不能大：它乘出来的就是**最坏那一包**的字节数，而这一包要在一只
#    10 秒的钟里走完（node 那侧等 SockJS 的 pong）。折算：
#      50 000 字 × 1.5 倍 × 2.8（实测 HTML/正文字节比）÷ 1024 = 205 KB
#      205 KB ÷ 50 KB/s = **4.1 秒** ✓（留了一倍多余量）
#    ⚠️ 2.8 是**线上真实正文**的比例（扒用户那三个最长对话渲染出来的）。
#       markdown 密的正文（表格/列表/代码块一段接一段）能到 5 倍以上 ——
#       tests/ui_v158/probe_histwin.py 的夹具就是这种，实测同一段窗口
#       236 KB。那是压力上限，不是常态。
#    写 3 的时候折算 8.2 秒 —— 自检里那条折算断言当场把这一版拦下来了
#    （这正是它存在的意义：预算改大到"发不完"，这一版修的东西就自己回来了）。
DSAPP_HIST_HARD_MULT <- 1.5

# ★★ V16.1 item 2：「显示更早的消息」最多能往回翻**几屏**。
#
#   用户原话：「主账号中，对话里显示更早的消息**无法正常加载出来**」。
#
#   2026-10-04 复现（tests/ui_v161/probe_histmore.py，50 KB/s 的慢链路 +
#   正文/思维链都像线上那样的夹具）—— 改前连点八次，**每一包都是整个窗口**：
#     打开 218 KB → 点 1 次 185 KB → 2 次 290 KB → 3 次 369 KB → 4 次 473 KB
#     → 5 次 578 KB → 6 次 683 KB → 7 次 **763 KB**
#   两个后果，一个比一个重：
#     ① 每一包都在变长，而这条链路的死线是 694 KB（180 秒心跳 × 3.65 KB/s，
#        见上面那段）—— 点到第七八次就顶穿，重连 → 自愈整页重载；
#     ② **更重的是它不会自己回去**：`hist_extra` 是个只增不减的计数器，
#        从此**每一次**历史重渲染（每写一条消息、每次 hist_ver）都要把那个
#        763 KB 再发一遍 = 3.5 分钟一包，必然心跳超时 → 重载 → 又回到那个
#        计数器…用户看到的就是"这个对话再也打不开了"。
#   所以真正要改的不是"多给一点预算"，是**别再让窗口随点击无限长大**。
#
#   改法是**分屏**：每一屏各自占一个 uiOutput（见 mod_chat.R 的 hist_pages），
#   点一次只把**新那一屏**发出去，已经发过的屏一个字节都不重发。
#   每屏的大小就是 DSAPP_HIST_BUDGET_C 那一套（末尾一段 + 预算），所以
#   单次点击的增量恒定在 ~155 KB（50 KB/s 上约 3 秒）—— **与点了几次无关**。
#
#   为什么是**固定** 10 屏、而不是想点几次点几次：
#     · 每屏都是真 DOM，10 屏 × 50 000 字 ≈ 1.5 MB 渲染量 —— 再多浏览器先扛不住；
#     · 10 屏往回 ≈ 50 万字，uid=1 那个最长的对话（74 条 / 89 万字）能翻到
#       差不多一半，231 条的那个能翻到三分之二。
#   翻到头就在原位说清楚（「前面还有 N 条，一次只取回这么多」），
#   **不做成一颗点了没反应的链接** —— 那正是这一版要修的那个症状。
DSAPP_HIST_MAX_PAGES <- 10L

# ★★★ V15.12：慢链路这件事，最后**不是**靠"把预算再调小一点"收的场。
#     上面那两条预算仍然有用（它们压的是每一包的**持续时间**），但把首屏
#     一路缩下去也保证不了安全 —— 原因如下，这一段是那件事的结论存档。
#
# 2026-10-03 线上只读取证（uid=1 / user1@example.com，客户端 198.51.100.7）：
#   · 那条链路实测**中位数 3.65 KB/s**（峰值 37.6 KB/s）—— 正是上面反复出现
#     的 50 KB/s 的 1/14；
#   · 每一次断线时 Send-Q 上还压着 **51 800 ~ 67 200 字节**，紧接着源端口就
#     换了（= 服务端关掉了那条连接）；
#   · 首屏总量：外壳 115 KB（普通用户）/ 116 KB（管理员；那 6 页在 V15.12 改
#     懒加载之前是 152 KB）+ 登录时自动打开的那个会话的历史窗口 ≈ 45 KB
#     ≈ **161 KB**。
#
# 关键的一步推理：**应用侧再缩也保证不了安全。**
#   SockJS 在 websocket 通道上每 `sockjs_heartbeat_delay` 秒发一个协议级 PING
#   （默认 **25** 秒），**10 秒**内收不到 pong 就
#   `session.close(3000, 'No response from heartbeat')`；那个 10 秒写死在
#   sockjs/lib/trans-websocket.js:144-159，配置改不了（RStudio 自己的规则
#   文件也承认 "an effective 10 second limit built in"）。
#   PING 与业务数据**共用一条 TCP 连接** → 排在积压后面 → pong 晚 Q/R 秒才到。
#   于是：只要首屏 K 字节 > 25 s × 3.65 KB/s ≈ **91 KB**，这条判据必然响 ——
#   而**外壳本身**（不含任何历史）就有 115 KB。在 3.65 KB/s 上，"首屏别触发
#   心跳超时"是应用代码做不到的事，把预算从 50 000 调到 20 000 也一样。
#
# 解法在**服务端配置**：`sockjs_heartbeat_delay` 25 秒 → **180 秒**
#   （改的是 /etc/shiny-server/shiny-server.conf；完整副本 + 理由 + 代价
#   写在 tests/ui_v158/shiny-server-v1512.conf，重装/换机器照抄那一份）。
#   判死线 = 3.65 KB/s × (180 + 10) ≈ **694 KB**。
#   而**实测今天最重的一屏**是 368 KB（外壳 115 KB + uid=11 那个正在写的长
#   对话的窗口，末尾两条一条 257 KB）= 余量 **1.9 倍**；链路慢到 2 KB/s 也还
#   活得下来。（先按 120 秒算过：只有 474 KB、余量 1.29 倍 —— 那条对话再长
#   一条巨回复就贴线，所以没停在 120。）
#   ⚠️ 代价（知情选择）：真死掉的客户端，服务端要 180+10 秒才发现（原 25+10），
#      这段时间它的 worker/session 多留一会儿。**并发上去、或要跑重会话之前，
#      回来重新权衡这一行。**
#   ⚠️⚠️ 但它**不是**对任意大的一包都成立：最末尾两条是**免预算**的
#      （DSAPP_HIST_FLOOR_MSG），实测单条消息最大能渲染出 384 KB，所以理论上
#      最坏的一屏 ≈ 880 KB，超出 180 秒能兜住的范围（要 240 秒以上，而那会让
#      死连接多占 worker 一分多钟）。**真正的解法是给单条消息的渲染封顶
#      （超长就折叠、点开再取）—— 那是产品改动，还没做。** 在那之前：哪天又
#      看到某个号循环重载，先量它的首屏字节数，再决定是抬这一行还是去做封顶。
#
# 另一半在客户端：V15.11 的刹车口径是"最近 3 分钟刷了 3 次"，而故障节奏正好
#   是 **120 秒**一次 —— 任意 180 秒的窗口里最多只装得下 2 次，**永远踩不下去**
#   （代码事实，见 www/app.js 的 DSAPP_HEAL_WINDOW_MS / DSAPP_HEAL_MAX）。
#   V15.12 换成"**只被'好起来'清零**"的计数 + 每失败一轮退避 20 秒 +
#   手动刷新清零，并把"已经自动重试 N 次"说给用户听。
#   两边缺一不可：服务端让断开**不再发生**，客户端保证万一再断了也**不会
#   变成一个无限重载的圈** —— 那正是用户看到的"页面崩溃"。
#   ⚠️ 两版的差别在**真实节奏（120 秒）**下才看得出来，压缩节奏下两版都会
#      在第 4 轮停手：新旧对照用 tests/ui_v158/brake_sim.js（拿两版的真代码
#      + 假时钟跑），浏览器探针 probe_heal_brake.py 验的是新版的四条行为。

