# =============================================================================
# 帮助页（V13.14 item 23）
#
# 用户原话：「23、帮助页面独立到左侧导航栏」。
#
# ★ 这一页原来不是一页，是**设置页的第四个二级页签**
#   （mod_settings.R 里的 nav_panel("帮助", value = "help")，V13.5 item 7 分的
#   四组之一）。现在它搬出来，成为左栏 `DSAPP_NAV_ITEMS` 里的一项
#   （R/uiprefs.R，value = "help"），和「言出法随」「设置」平级。
#
#   为什么这件事不只是"挪个位置"：
#     · 搬之前，用户找帮助的路径是**设置 → 帮助**。而"设置"这两个字在用户
#       心里是"改我自己的东西"，出事的时候没人会先想到去那儿；
#     · 设置页那四个页签是按"用户来这一页要干的事"分的（界面 / 执行 / 账号），
#       帮助**不是同一类事** —— 前三个都是"改什么"，它是"出问题了怎么办"。
#       它挂在那里，是四组里唯一的异类（V13.9 item 11 把「保存并开始使用」
#       从这一页赶走，说的也是同一件事：这一页不该承担"改设置"的职责）。
#
# ⚠️ 这一页**没有 server**。整页是静态内容，没有任何 input —— 所以 app.R 那
#    边只调 mod_help_ui()，没有对应的 mod_help_server()。将来要往这里加东西
#    （比如"把当前配置导出成一段文本给客服"），先加 server，别把逻辑塞进 ui。
#
# ⚠️ `ns <- NS(id)` 现在**只用在一个地方**（容器那个 id），这是有意的：模块
#    的 UI 一旦不带命名空间，后面有人往这里加一个 textInput("foo") 就会和别
#    的页撞 id —— 而 Shiny 撞 id 不报错，只是那个 input 永远拿不到值（同
#    mod_settings.R 顶部那段「Duplicate input ID」的说明）。
# =============================================================================

mod_help_ui <- function(id) {
  ns <- NS(id)

  div(class = "dsapp-page", id = ns("page"),

    # ---- 客服微信 / 公众号（V13.9 item 12）----
    #
    # 用户原话：「帮助页面留一下微信二维码，或者留Rmarkdown2026开头那个
    # 页面」。
    #
    # 他说的那张「Rmarkdown2026开头那个页面」是一张**图**，不是页面 ——
    # 就是各个教程仓库 data/ 下面那张同名海报（Biomamba 生信基地的
    # 宣传页，1800×766），左上角是客服微信码、右上角是公众号码。
    # 两个说法指向的是同一件事，所以这里把**整张海报**放上来：二维码
    # 在里面，用户想看的其它信息（全程班、订阅资料、服务器）也在里面，
    # 不用再问"那个页面在哪"。
    #
    # ⚠️ 图在 www/help-wx.png —— 这是 **www/ 那条约定的一个例外**，
    #    理由写在 R/utils.R 里 dsapp_logo 那一段旁边（搜 "help-wx"）。
    #    一句话版：那张约定是冲着"每台部署各不相同的 VI"和"不该公开的
    #    东西"定的，而这张海报是随代码走的、本来就要给人看的宣传图。
    #
    # ⚠️ 点击在新标签页打开原图。海报上的字缩到侧栏宽度下会糊，而用户
    #    多半是想**看清二维码去扫** —— 新标签页里是原始尺寸。
    #    rel="noopener noreferrer" 的理由同页脚那个算力入口。
    card(
      card_header(icon("headset"), " 客服微信 / 公众号"),
      card_body(
        p(class = "small text-muted mb-2",
          "加客服微信可以领教程资料、报问题；公众号会发更新和教程。"),
        tags$a(href = dsapp_asset("help-wx.png"),
               target = "_blank", rel = "noopener noreferrer",
               title = "点开看大图（方便扫码）",
               tags$img(src = dsapp_asset("help-wx.png"),
                        class = "dsapp-help-img",
                        alt = "Biomamba 生信基地 —— 客服微信二维码、公众号二维码、全程班与订阅资料")),
        p(class = "small text-muted mt-2 mb-0",
          icon("headset"), " 客服微信：", tags$b("Biomamba_zhushou"))
      )
    ),

    # ★★ V13.9 item 11 用户原话：
    #    「保存并开始使用不应该出现在帮助页面，而是应该出现在其它设置
    #      页面的底部」
    #
    #    这张卡（「保存并开始使用」+「保存并返回对话」+ 就绪徽章）原来
    #    长在这一页的最上面。它放错了地方：**帮助页是"看说明"的地方**，
    #    而这张卡是"改完设置该走了"——用户改皮肤在「界面」页、改硬件在
    #    「执行」页、改密码在「账号」页，改完抬头一看，手边没有出口，
    #    得先想到"哦要去帮助页才有那个按钮"。而帮助页本身一个字都不用改，
    #    这个按钮出现在那里反而像是这一页的一部分。
    #
    #    现在它挂到设置页那三栏各自的**底部**（见 dsapp_back_card 的调用
    #    点），改完就地能走。这一页只剩说明。
    #
    # ⚠️ V13.14 item 23 把这一页搬到左栏之后，这个分工**更要紧**了：现在
    #    它是一级页面，用户从任意地方一点就到，"这里冒出一个返回对话的按钮"
    #    会比以前更突兀。别加回来。
    #
    # ---- 使用说明（占位，原「服务器环境」卡片的位置）----
    #
    # 这里原本有一张「服务器环境」卡片，逐行列出 Rscript / Python /
    # conda 的绝对路径、数据目录、文件区、运行身份（登录用户名）、
    # 执行超时、内存和 CPU 上限。用户要求撤掉（item 3），理由是这些
    # 属于运维信息，不该出现在面向分析人员的界面上。
    #
    # ⚠️ 撤掉同时也是**少一处信息泄露**，别再加回来：这个应用没有登录，
    #    任何能打开这个页面的人都能看到这些。其中的绝对路径直接告诉了
    #    对方服务器上装了什么、数据放在哪、以哪个账号在跑 —— 对准备
    #    构造路径穿越或提权的人来说，这是免费的一份侦察报告。
    #    运维要看这些应该去看服务端日志，不是看用户的设置页。
    card(
      card_header(icon("circle-question"), " 需要帮助？"),
      card_body(
        p(class = "text-muted small mb-2",
          "运行环境由平台在后台自动准备，你不需要手动配置，也不需要选择。"),
        tags$ul(class = "small text-muted mb-0 ps-3",
          tags$li("第一次提交任务时，平台会为这个对话单独准备一套运行环境，",
                  "需要多等一会儿；之后的执行直接复用。"),
          # ⚠️ 这里原来写的是 `**这个对话自己的环境**`。Shiny 的
          #    card_body/p() 不做 Markdown 渲染，那两对星号会**原样显示**
          #    在界面上。要加粗只能用 tags$b()。
          tags$li("想装额外的 R / Python 包，去「环境」页，装进的是",
                  tags$b("这个对话自己的环境"), "，不会影响别人。"),
          tags$li("代码和数据默认都留在这个对话自己的工作区里，",
                  "别人看不到；要留到长期目录就显式「发布」到文件管理区。"),
          # ★ V13.1 item 8：这句原来是「文件管理区里别人传的文件你能看
          #   也能下载 —— 这是刻意的，那是个公共区」。**它是反的。**
          #   管理区从 V13 起按账号物理隔离（data/files/u<N>/，
          #   见 dsapp_config_user 的 files_dir），别人的目录你连路径
          #   都拼不出来。原文会让用户以为传上去是给全站看的。
          tags$li("文件管理区是", tags$b("按账号隔离的"),
                  "—— 你在里面只看到自己的文件，别人也看不到你的。")
        ),
        # 版本号放在这里是为了回答一个具体问题：出了事第一句话多半是
        # "服务器上跑的是哪一版"。这个应用是手工拷到 /srv/shiny-server
        # 部署的，没有别的途径能看出当前是哪一版。改代码时顺手加一
        # （DSAPP_VERSION，在 config.R）。
        # ---- 平台限制（V6 item 6）----
        #
        # ⚠️ 必须**如实**说，不能因为"界面好看"就省掉。服务器版靠 bash 的
        #    ulimit 限住 CPU 时间/内存/进程数，Windows 上没有这套东西
        #    （见 R/platform.R）—— 在那里跑的代码就是以用户自己的账号
        #    权限、没有任何限额地在跑。用户有权在跑之前知道这件事。
        #    dsapp_platform_note() 在有限制的平台上返回 NULL，这一块
        #    就整段不渲染（不留一条空警告）。
        if (nzchar(dsapp_platform_note() %||% ""))
          div(class = "alert alert-warning small mt-3 mb-0",
              icon("triangle-exclamation"), " ",
              dsapp_md_inline(dsapp_platform_note())),
        p(class = "text-muted small mt-3 mb-0",
          sprintf("应用版本：V%s", DSAPP_VERSION))
      )
    )
  )
}
